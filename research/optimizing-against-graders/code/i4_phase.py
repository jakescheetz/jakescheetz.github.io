#!/usr/bin/env python3
"""§9 I4 phase check, as amended in §9 I11 (written before any rolling checkpoint was evaluated). Dev only.

  .venv/bin/python i4_phase.py [--out results/b2/i4-phase]     -> OUT.{md,json}

For each of the 10 batch-2 A0 runs' two non-final rolling checkpoints (evaluated on the run's own state × 8,
seeds 1000-1007, into ~/roms/runs/<run>/eval-i4/ by evaluate.py):
  phase = (step mod 131,072) / 131,072   (8 envs reset together every 16,384 steps)
  ratio = mean P ÷ mean(the run's 4M snapshot P, its 5M snapshot P), both from eval-dev-primary (own state × 8)
Pre-registered (I11, 'Ruling on the groups': thresholds on ACTUAL phases, the named lists void): late phase (≥ 86 %)
ratio ≤ 0.7 in ≥ 2 of 3; early phase (≤ 12 %) ratio ≥ 0.8 in ≥ 3 of 4. D1-s2 4,699,136 (85.2 %) and D1-s4 4,472,832
(12.5 %) are in neither group and are marked.
Descriptive: ratio and T against phase for all 20.
"""
import argparse
import json
from pathlib import Path

RUNS = Path.home() / "roms" / "runs"
CYCLE = 131_072
A0 = [f"b2-A0-D{d}-s{s}" for d in (1, 2) for s in range(1, 6)]
REF = (4_000_768, 5_000_192)
NEAR = {("b2-A0-D1-s2", 4_699_136), ("b2-A0-D1-s4", 4_472_832)}    # just outside a threshold: neither group (ruling)


def jl(p):
    return [json.loads(l) for l in open(p) if l.strip()]


def mean(v):
    return sum(v) / len(v)


def run_rows(run):
    st = json.loads((RUNS / run / "config.json").read_text())["state"]
    ref = {}
    for r in jl(RUNS / run / "eval-dev-primary" / "episodes.jsonl"):
        ref.setdefault(r["step"], []).append(r)
    snap = {m: (mean([r["P"] for r in ref[m]]), mean([r["T"] for r in ref[m]]), len(ref[m])) for m in REF}
    base = mean([snap[m][0] for m in REF])
    out = []
    by = {}
    for r in jl(RUNS / run / "eval-i4" / "episodes.jsonl"):
        assert r["state"] == st
        by.setdefault(r["step"], []).append(r)
    for step, rs in sorted(by.items()):
        ph = (step % CYCLE) / CYCLE
        P, T = mean([r["P"] for r in rs]), mean([r["T"] for r in rs])
        out.append({"run": run, "state": st, "step": step, "phase": round(ph, 4), "n": len(rs),
                    "P": round(P, 2), "T": round(T, 3), "P_4M": round(snap[REF[0]][0], 2), "P_5M": round(snap[REF[1]][0], 2),
                    "T_4M": round(snap[REF[0]][1], 3), "T_5M": round(snap[REF[1]][1], 3), "ratio": round(P / base, 3),
                    "group": "late" if ph >= 0.86 else "early" if ph <= 0.12 else
                    "neither (near boundary)" if (run, step) in NEAR else "mid"})
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=str(Path(__file__).resolve().parent / "results" / "b2" / "i4-phase"))
    a = ap.parse_args()
    rows = [x for r in A0 for x in run_rows(r)]
    late = [r for r in rows if r["group"] == "late"]
    early = [r for r in rows if r["group"] == "early"]
    nl, ne = sum(r["ratio"] <= 0.7 for r in late), sum(r["ratio"] >= 0.8 for r in early)
    pl, pe = nl >= 2, ne >= 3
    res = {"checkpoints": len(rows), "episodes_each": sorted({r["n"] for r in rows}),
           "late": {"n": len(late), "ratio_le_0.7": nl, "prediction_holds": pl},
           "early": {"n": len(early), "ratio_ge_0.8": ne, "prediction_holds": pe},
           "reading": ("both predictions hold: phase hypothesis supported (evidence, not a test)" if pl and pe else
                       "neither prediction holds: phase hypothesis not supported" if not (pl or pe) else
                       "split result: " + ("late holds, early does not" if pl else "early holds, late does not")),
           "rows": rows}
    L = ["# §9 I4 phase check (amended in I11): A0 rolling checkpoints, own state × 8, dev only", "",
         "phase = (step mod 131,072) ÷ 131,072; ratio = P ÷ mean(4M, 5M snapshot P of the same run, own state × 8). "
         "Pre-registered in §9 I11 before any of these was read: late (≥ 86 %) ratio ≤ 0.7 in ≥ 2 of 3; "
         "early (≤ 12 %) ratio ≥ 0.8 in ≥ 3 of 4 (I11 ruling: thresholds on actual phases). Generated by `i4_phase.py`.", "",
         f"**Late phase:** {nl} of {len(late)} have ratio ≤ 0.7 → prediction {'holds' if pl else 'does not hold'}.  ",
         f"**Early phase:** {ne} of {len(early)} have ratio ≥ 0.8 → prediction {'holds' if pe else 'does not hold'}.  ",
         f"**Reading:** {res['reading']}.", "",
         "| run | step | phase | group | P (n=8) | T | P 4M / 5M | T 4M / 5M | ratio |", "|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: r["phase"]):
        L.append(f"| {r['run']} | {r['step']:,} | {r['phase']:.1%} | {r['group']} | {r['P']} | {r['T']} | "
                 f"{r['P_4M']} / {r['P_5M']} | {r['T_4M']} / {r['T_5M']} | {r['ratio']} |")
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".json").write_text(json.dumps(res, indent=1))
    out.with_suffix(".md").write_text("\n".join(L) + "\n")
    print("\n".join(L[4:7]))


if __name__ == "__main__":
    main()
