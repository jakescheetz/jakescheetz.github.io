#!/usr/bin/env python3
"""Markdown table of every U window in an evaluate.py output (needs --window-stats), for review.

  python3 u_report.py ~/roms/runs/A0-D1-s0/eval-final [--out results/A0-D1-s0-final-u.md]

Reads windows.jsonl + episodes.jsonl + summary.json; stdlib only, no ROM. Per U window: the window's
stats (P in W, the checkpoint's U threshold, distinct tiles, modal-row fraction, modal-tile arrivals,
k-gram repeats, P on revisits split by term), the maps it spent its rows on, the P of the windows
around it, and the episode's T, P and maps visited.
"""
import argparse
import json
from collections import Counter
from pathlib import Path

MAPS = {0x00: "Pallet Town", 0x01: "Viridian City", 0x02: "Pewter City", 0x0C: "Route 1", 0x0D: "Route 2",
        0x21: "Route 22", 0x25: "Red's house 1F", 0x26: "Red's house 2F", 0x27: "Blue's house",
        0x28: "Oak's Lab", 0x29: "Viridian Pokecenter", 0x2A: "Viridian Mart", 0x2B: "Viridian school", 0x2C: "Viridian nickname house",
        0x2D: "Viridian Gym", 0x2F: "Viridian Forest north gate", 0x30: "Route 2 trade house", 0x31: "Route 2 gate",
        0x32: "Viridian Forest south gate", 0x33: "Viridian Forest",
        0x36: "Pewter Gym", 0x3A: "Pewter Pokecenter"}


# names from pret/pokered constants/map_constants.asm
def name(h):
    i = int(h, 16)
    return f"{MAPS.get(i, '?')} ({h})"


def rows(p):
    with open(p) as f:
        return [json.loads(line) for line in f if line.strip()]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("eval_dir")
    ap.add_argument("--out")
    a = ap.parse_args()
    d = Path(a.eval_dir).expanduser()
    wins = rows(d / "windows.jsonl")
    eps = {(e["ckpt"], e["state"], e["seed"]): e for e in rows(d / "episodes.jsonl")}
    summ = json.loads((d / "summary.json").read_text())
    thr = summ["pilot_go_no_go"].get("u_threshold_per_ckpt", {})
    by_ep = {}
    for w in wins:
        by_ep.setdefault((w["ckpt"], w["state"], w["seed"]), []).append(w)
    order = lambda k: (int(k[0].split("-")[1].split(".")[0]), k[1], k[2])
    us = [w for w in wins if "U" in w["fired"]]
    out = [f"# U firings: {summ['run_id']} ({d.name})", "",
           f"{len(us)} U windows of {len(wins)} (W = 2048, stride 1024), in "
           f"{len({(w['ckpt'], w['state'], w['seed']) for w in us})} of {len(eps)} episodes. "
           f"Generated by `u_report.py` from `{d.name}/` (eval created {summ.get('created')}).", "",
           "## Per checkpoint and state", "",
           "| ckpt | U threshold (top decile) | state | U windows | episodes with U |", "|---|---|---|---|---|"]
    labels = Counter(w.get("u_kind", "n/a") for w in us)
    out[2:2] = [f"U labels: " + ", ".join(f"{k} {v}" for k, v in sorted(labels.items())) + ".", ""]
    per = Counter((w["ckpt"], w["state"]) for w in us)
    per_ep = Counter((k[0], k[1]) for k in {(w["ckpt"], w["state"], w["seed"]) for w in us})
    for (c, s) in sorted(per, key=lambda k: (int(k[0].split("-")[1].split(".")[0]), k[1])):
        out.append(f"| {c} | {thr.get(c)} | {s} | {per[(c, s)]} | {per_ep[(c, s)]}/{summ['episodes_per']} |")
    maps_all = Counter()
    for w in us:
        maps_all.update(w["maps"])
    out += ["", "Rows spent per map, all U windows: " +
            ", ".join(f"{name(m)} {n}" for m, n in maps_all.most_common()), ""]
    out += ["## Windows", "",
            "P around = P in W of the windows before and after (same episode); the U window is bold. "
            "P by term = P in W split explore/seen/level/heal; rev = the same on revisited tiles. U label = novelty "
            "(>= 90% of P is explore on new tiles on route maps) or review (§9 U review). off-path = share of rows "
            "on O's off-path maps. Other fired = detectors also on "
            "the window (only K can be, by definition).", "",
            "| ckpt | state | seed | win | steps | P in W | thr | distinct tiles | modal frac | modal arrivals | kgram rep | P by term e/s/l/h | rev e/s/l/h | U label | off-path | maps (rows) | P around | other fired | ep T | ep P | ep maps visited |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for w in sorted(us, key=lambda w: order((w["ckpt"], w["state"], w["seed"])) + (w["window"],)):
        k = (w["ckpt"], w["state"], w["seed"])
        ep, seq = eps[k], by_ep[k]
        i = next(j for j, x in enumerate(seq) if x["window"] == w["window"])
        around = " ".join((f"**{x['p_in_w']:g}**" if x is w else f"{x['p_in_w']:g}") for x in seq[max(0, i - 2): i + 3])
        maps = "; ".join(f"{name(m)} {n}" for m, n in sorted(w["maps"].items(), key=lambda t: -t[1]))
        rev = "/".join(f"{w[f'p_rev_{t}']:g}" for t in ("explore", "seen", "level", "heal"))
        terms = "/".join(f"{w[f'p_{t}']:g}" if f"p_{t}" in w else "n/a" for t in ("explore", "seen", "level", "heal"))
        label, offp = w.get("u_kind", "n/a"), w.get("offpath_fraction")
        offp = f"{offp:.2f}" if offp is not None else "n/a"
        other = ",".join(f for f in w["fired"] if f != "U") or "-"
        out.append(f"| {w['ckpt']} | {w['state']} | {w['seed']} | {w['window']} | {w['start']}-{w['end']} | "
                   f"{w['p_in_w']:g} | {thr.get(w['ckpt'])} | {w['distinct_tiles']} | {w['modal_row_fraction']:.2f} | "
                   f"{w['tile_arrivals']} | {w['kgram_repeats']} | {terms} | {rev} | {label} | {offp} | {maps} | {around} | {other} | "
                   f"{ep['T']} | {ep['P']:g} | {', '.join(name(m) for m in ep['maps_visited'])} |")
    text = "\n".join(out) + "\n"
    if a.out:
        Path(a.out).write_text(text)
        print(f"wrote {a.out} ({len(us)} U windows)")
    else:
        print(text)


if __name__ == "__main__":
    main()
